/**
 * Markdown reference pages for the coaching knowledge, generated from the
 * same CSVs the app loads (data/coaching/*.csv). Pure: CSV text in, files out.
 * The CSVs stay the single source of truth; these pages are for people to
 * read and link to, and a test keeps them in sync.
 */
import { parseCsvRecords } from "./csv.js";

export type CoachingDocsInput = {
  philosophy: string;
  lessons: string;
  situations: string;
  stories: string;
  insights: string;
  rulesFacts: string;
};

const HEADER = "<!-- GENERATED by `npm run rules:build` from data/coaching/*.csv. Edit the CSV, not this file. -->\n\n";
const list = (raw: string | undefined) => (raw ?? "").split(";").map((x) => x.trim()).filter(Boolean);
const status = (r: Record<string, string>) =>
  /^(true|t|1)$/i.test(r.verified ?? "") ? `Reviewed${r.verified_by ? ` by ${r.verified_by}` : ""}` : "Draft, not yet reviewed";
const anchor = (id: string) => id.toLowerCase();

export function buildCoachingDocs(input: CoachingDocsInput): Record<string, string> {
  const lessons = parseCsvRecords(input.lessons);
  const situations = parseCsvRecords(input.situations);
  const stories = parseCsvRecords(input.stories);
  const insights = parseCsvRecords(input.insights);
  const facts = new Map(parseCsvRecords(input.rulesFacts).map((f) => [f.fact_id ?? "", f]));
  const lessonTitle = new Map(lessons.map((l) => [l.lesson_id ?? "", l.title ?? ""]));
  const situationName = new Map(situations.map((s) => [s.situation_id ?? "", s.name ?? ""]));
  const lessonLink = (id: string) => `[${lessonTitle.get(id) ?? id}](lessons.md#${anchor(id)})`;
  const situationLink = (id: string) => `[${situationName.get(id) ?? id}](situations.md#${anchor(id)})`;

  const lessonsMd =
    HEADER +
    "# Lessons\n\nThe life lessons DiamondAgentIQ teaches. They aren't tied to an age; they show up whenever the game brings them up. Every answer carries one.\n\n" +
    lessons
      .map((l) => {
        const angles = [
          ["Player", l.for_player],
          ["Coach", l.for_coach],
          ["Parent", l.for_parent],
          ["Umpire", l.for_umpire],
        ]
          .filter(([, v]) => v)
          .map(([who, v]) => `- **${who}:** ${v}`)
          .join("\n");
        return `<a id="${anchor(l.lesson_id ?? "")}"></a>\n## ${l.lesson_id}: ${l.title}\n\n${l.principle}\n\n**Beyond the diamond:** ${l.life_lesson}\n\n${angles}\n\nMoments: ${list(l.tags).map((t) => `\`${t}\``).join(", ")}. ${status(l)}.\n`;
      })
      .join("\n");

  const situationsMd =
    HEADER +
    "# Situations\n\nHow the offense and defense should react in specific game states. A situation applies only where its rule is in effect; the linked rule facts say where.\n\n" +
    situations
      .map((s) => {
        const ruleLines = list(s.rule_fact_codes)
          .map((code) => {
            const f = facts.get(code);
            return f ? `- ${code} (${f.sanction}${f.division ? `, ${f.division}` : ""}): ${f.summary}` : `- ${code}`;
          })
          .join("\n");
        const state = [s.bases && `bases: ${s.bases}`, s.outs && `outs: ${s.outs}`, s.count && `count: ${s.count}`].filter(Boolean).join(" · ");
        return `<a id="${anchor(s.situation_id ?? "")}"></a>\n## ${s.situation_id}: ${s.name}\n\n${state}\n\n**Offense:** ${s.offense}\n\n**Defense:** ${s.defense}\n\n${s.common_mistakes ? `**Common mistakes:** ${s.common_mistakes}\n\n` : ""}**Where the rule applies:**\n${ruleLines || "- (no rule facts linked)"}\n\nLessons: ${list(s.lesson_ids).map(lessonLink).join(", ") || "none"}. ${status(s)}.\n`;
      })
      .join("\n");

  const storiesMd =
    HEADER +
    "# Stories\n\nReal coaching moments, in the coach's words. Anonymized: no players, teams, leagues, places or years.\n\n" +
    stories
      .map(
        (s) =>
          `<a id="${anchor(s.story_id ?? "")}"></a>\n## ${s.story_id}: ${s.title}\n\n${s.story}\n\nLessons: ${list(s.lesson_ids).map(lessonLink).join(", ") || "none"}. Situations: ${list(s.situation_ids).map(situationLink).join(", ") || "none"}. ${status(s)}.\n`,
      )
      .join("\n");

  const byTopic = new Map<string, Record<string, string>[]>();
  for (const i of insights) byTopic.set(i.topic ?? "", [...(byTopic.get(i.topic ?? "") ?? []), i]);
  const insightsMd =
    HEADER +
    "# Coaching insights\n\nPractical tips by topic, with the ages and audience they're for.\n\n" +
    [...byTopic.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(
        ([topic, rows]) =>
          `## ${topic.replace(/_/g, " ")}\n\n` +
          rows
            .map(
              (i) =>
                `### ${i.insight_id}: ${i.situation}\n\nAges ${i.age_min || "any"}-${i.age_max || "any"} · for ${i.audience} · ${i.sport} · source \`${i.source_id}\`\n\n${i.insight}\n\n${i.why ? `**Why:** ${i.why}\n\n` : ""}${i.try_this ? `**Try this:** ${i.try_this}\n\n` : ""}${status(i)}.\n`,
            )
            .join("\n"),
      )
      .join("\n");

  const readme =
    HEADER +
    "# DiamondAgentIQ coaching references\n\nWhat the agents teach from, as readable pages. The data lives in `data/coaching/*.csv`; see `data/coaching/README.md` to add or change material.\n\n" +
    `- [Lessons](lessons.md) (${lessons.length}): the philosophy, with what it means for players, coaches, parents and umpires\n` +
    `- [Situations](situations.md) (${situations.length}): game states and how offense and defense react\n` +
    `- [Stories](stories.md) (${stories.length}): real coaching moments\n` +
    `- [Coaching insights](insights.md) (${insights.length}): practical tips by topic\n\n` +
    "## Learning philosophy\n\n" +
    input.philosophy.replace(/^DiamondAgentIQ learning philosophy:\n/, "") +
    "\n";

  return {
    "docs/coaching/README.md": readme,
    "docs/coaching/lessons.md": lessonsMd,
    "docs/coaching/situations.md": situationsMd,
    "docs/coaching/stories.md": storiesMd,
    "docs/coaching/insights.md": insightsMd,
  };
}
